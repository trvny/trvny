export function staticPaths(page) {
  return page.path.endsWith("/")
    ? [page.path, page.path.slice(0, -1), "/" + page.file]
    : [page.path, "/" + page.file];
}

function inject(html, tag, content, marker = "hub-shell") {
  const closing = tag === "head" ? /<\/head\s*>/gi : tag === "body" ? /<\/body\s*>/gi : null;
  if (!closing) throw new Error("Unsupported shell tag");
  const start = `<!-- ${marker}:${tag}:start -->`;
  const end = `<!-- ${marker}:${tag}:end -->`;
  if (html.includes(start)) {
    const from = html.indexOf(start);
    const to = html.indexOf(end, from);
    if (to < 0) throw new Error("Incomplete hub shell: " + tag);
    html = html.slice(0, from) + html.slice(to + end.length);
  }
  // Controlled HTML inputs only. Fail closed if their layout changes.
  const matches = [...html.matchAll(closing)];
  if (matches.length !== 1) throw new Error("Expected one closing " + tag + " tag");
  const index = matches[0].index;
  return html.slice(0, index) + start + content + end + html.slice(index);
}

export function renderStaticShell(html, page) {
  const lang = /<html\b[^>]*\slang=["']([^"']+)["']/i.exec(html)?.[1];
  if (lang !== page.lang) throw new Error("Unexpected document language: " + page.file);
  const document = page.page === "token-worldcup" ? renderWorldcupPolish(html) : html;
  return inject(inject(document, "head", pageShellHead(page.path, page.page)), "body", NAV_BODY);
}

const HEADER_MARKER = "# Generated by build-static-shell.mjs; edit STATIC_PAGES instead.";
export function staticHeaders() {
  return HEADER_MARKER + "\n" + STATIC_PAGES.flatMap(page => staticPaths(page).map(path => [
    path,
    "  Content-Language: " + page.lang,
    "  Cache-Control: public, max-age=0, s-maxage=120, stale-while-revalidate=300",
    "  Link: " + (page.markdown ? "<" + page.markdown + '>; rel="alternate"; type="text/markdown", ' : "") + '</llms.txt>; rel="describedby"',
    ...(page.noindex ? ["  X-Robots-Tag: noindex, follow"] : []),
  ].join("\n"))).join("\n") + "\n" + [
    "/teksty/githubowa-kraina/atlas.json",
    "  Content-Type: application/json; charset=utf-8",
    "  Access-Control-Allow-Origin: *",
    "/.well-known/ard.json",
    "  Content-Type: application/ard+json; charset=utf-8",
    "  Access-Control-Allow-Origin: *",
    "/.well-known/ai-catalog.json",
    "  Content-Type: application/ai-catalog+json; charset=utf-8",
    "  Access-Control-Allow-Origin: *",
  ].join("\n") + "\n";
}

export async function writeStaticShell(dir) {
  const routes = JSON.parse(await readFile(new URL("_routes.json", dir), "utf8"));
  for (const page of STATIC_PAGES) {
    const excluded = staticPaths(page).map(path => routes.exclude.includes(path));
    // A pre-rendered Markdown counterpart needs Functions for Accept negotiation.
    if (!excluded.every(value => value === !page.markdown)) {
      throw new Error("Static route policy mismatch: " + page.path);
    }
  }
  const headersFile = new URL("_headers", dir);
  const previous = await readFile(headersFile, "utf8").catch(error => {
    if (error.code === "ENOENT") return "";
    throw error;
  });
  if (previous && !previous.startsWith(HEADER_MARKER)) throw new Error("Refusing to overwrite manual _headers");
  // Validate all documents before writing any output.
  const documents = await Promise.all(STATIC_PAGES.map(async page => {
    const file = new URL(page.file, dir);
    const raw = await readFile(new URL(page.generatedFrom ?? page.file, dir), "utf8");
    return [file, renderStaticShell(page.generatedFrom ? renderWorldcupEnglish(raw) : raw, page)];
  }));
  const worldcupFile = new URL("teksty/token-worldcup/index.html", dir);
  const rows = worldcupData(await readFile(worldcupFile, "utf8"));
  await Promise.all(documents.map(async ([file, html]) => {
    await mkdir(new URL(".", file), { recursive: true });
    await writeFile(file, html);
  }));
  await writeFile(new URL("teksty/token-worldcup/dataset.json", dir), JSON.stringify(rows, null, 2) + "\n");
  await writeFile(headersFile, staticHeaders());
}

