#!/usr/bin/env python3
"""Regenerate functions/_shared/model-icons.js from lobe-icons.

Ports modelMappings (src/features/modelConfig.ts, MIT) to plain data: keyword
regexes -> static-svg icon name, first match wins (same as upstream ModelIcon).

  npm pack @lobehub/icons-static-svg@VERSION && tar xzf lobehub-icons-static-svg-*.tgz
  python3 scripts/sync_model_icons.py --ref <lobe-icons commit> --version VERSION --icons package/icons

Also writes Verdana-Bold-ish label widths (DejaVu Sans Bold 11px x1.07) for badge layout.
"""
import argparse
import json
import re
import urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "functions" / "_shared" / "model-icons.js"
SRC = "https://raw.githubusercontent.com/lobehub/lobe-icons/{ref}/src/features/modelConfig.ts"
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"


def parse(ts: str) -> list[dict]:
    imports = dict(re.findall(r"import (\w+) from '@/(\w+)';", ts))
    body = ts[ts.index("export const modelMappings"):]
    entries = []
    for m in re.finditer(r"\{\s*Icon:\s*(\w+),\s*keywords:\s*\[(.*?)\]", body, re.S):
        name = imports[m.group(1)]
        # TS single-quoted literals; '\\d' in source is regex \d
        kws = [k.replace("\\\\", "\\") for k in re.findall(r"'((?:[^'\\]|\\.)*)'", m.group(2))]
        entries.append({"icon": name.lower(), "keywords": kws})
    return entries


def widths() -> dict[str, float]:
    from PIL import ImageFont

    font = ImageFont.truetype(FONT, 11)
    return {chr(c): round(font.getlength(chr(c)) * 1.07, 2) for c in range(32, 127)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", required=True, help="lobe-icons commit SHA")
    ap.add_argument("--version", required=True, help="@lobehub/icons-static-svg version")
    ap.add_argument("--icons", required=True, type=Path, help="unpacked package/icons dir")
    a = ap.parse_args()

    ts = urllib.request.urlopen(SRC.format(ref=a.ref), timeout=30).read().decode()
    entries = []
    for e in parse(ts):
        if (a.icons / f"{e['icon']}-color.svg").exists():
            e["color"] = True
        elif not (a.icons / f"{e['icon']}.svg").exists():
            raise SystemExit(f"missing icon {e['icon']}")
        entries.append(e)

    OUT.write_text(
        "// Generated by scripts/sync_model_icons.py - do not edit.\n"
        f"// lobe-icons {a.ref} (MIT), @lobehub/icons-static-svg@{a.version}.\n"
        f"export const LOBE_VERSION = {json.dumps(a.version)};\n\n"
        "// First match wins; keywords are case-insensitive regexes.\n"
        "export const MODEL_ICONS = [\n"
        + "".join(f"  {json.dumps(e, ensure_ascii=False)},\n" for e in entries)
        + "];\n\n"
        "// Label widths in px (Verdana Bold 11px approximation).\n"
        f"export const CHAR_WIDTHS = {json.dumps(widths(), ensure_ascii=False)};\n"
    )
    print(f"{len(entries)} mappings -> {OUT}")


if __name__ == "__main__":
    main()
